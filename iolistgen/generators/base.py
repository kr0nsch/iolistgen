"""Протокол генератора, опции и контекст записи файлов.

Генератор получает проверенную модель ``IoList`` (ошибок в перечне нет), каталог вывода и
контекст: значения опций, настройки проекта и запись файлов. Контекст пишет файлы
идемпотентно: UTF-8 без BOM, переводы строк LF, файл перезаписывается только при изменении
содержимого — повторная генерация из того же перечня ничего не меняет.

Команда ``iolistgen generate`` создаёт контексты с отложенной записью (``deferred``): файлы
всех генераторов собираются в памяти и пишутся (``commit``), только если все генераторы
отработали без ошибок, а с ``--strict`` — и без предупреждений. Сбой одного генератора не
оставляет в проекте новый ST рядом со старыми картами обмена.

Заголовок каждого файла — ``AUTO-GENERATED by iolistgen <версия> — не редактировать;
источник: <файл перечня>`` и строка с SHA-256 перечня и именем генератора. Времени генерации в
заголовке нет (иначе каждый запуск менял бы все файлы); его добавляет только явный ключ
``iolistgen generate --timestamp``.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal, Protocol, runtime_checkable

from iolistgen.config import Config
from iolistgen.model import IoList, SourceInfo

OptionKind = Literal["str", "bool", "int", "choice"]
OptionValue = str | bool | int

AUTO_GENERATED = "AUTO-GENERATED"
DO_NOT_EDIT = "не редактировать"

_TRUE = frozenset({"1", "true", "yes", "on", "да"})
_FALSE = frozenset({"0", "false", "no", "off", "нет"})


class OptionError(ValueError):
    """Значение опции генератора не подходит к её типу."""


class GenerationError(Exception):
    """Генератор не может построить файлы по этому перечню (сообщение — для пользователя)."""


@dataclass(frozen=True)
class GeneratorOption:
    """Опция генератора: задаётся в ``[generators.<имя>]`` или ключом ``--set <имя>.<опция>=...``."""

    name: str
    help: str
    kind: OptionKind = "str"
    default: OptionValue = ""
    choices: tuple[str, ...] = ()

    def parse(self, value: object) -> OptionValue:
        """Привести значение (из TOML — уже типизированное, из командной строки — строку)."""
        if self.kind == "bool":
            if isinstance(value, bool):
                return value
            text = str(value).strip().casefold()
            if text in _TRUE:
                return True
            if text in _FALSE:
                return False
            raise OptionError(f"опция {self.name}: «{value}» — не логическое значение (true или false)")
        if self.kind == "int":
            if isinstance(value, bool):
                raise OptionError(f"опция {self.name}: ожидается целое число")
            try:
                return int(str(value).strip())
            except ValueError:
                raise OptionError(f"опция {self.name}: «{value}» — не целое число") from None
        text = str(value)
        if self.kind == "choice" and text not in self.choices:
            raise OptionError(f"опция {self.name}: «{text}» — допустимо {', '.join(self.choices)}")
        return text


@dataclass(frozen=True)
class OutputFile:
    """Файл, который записал генератор: путь и изменился ли он в этом прогоне."""

    path: Path
    changed: bool


@dataclass
class GeneratorContext:
    """Контекст одного запуска генератора."""

    generator: str
    out_dir: Path
    options: Mapping[str, OptionValue]
    config: Config
    source: SourceInfo
    version: str
    outputs: list[OutputFile] = field(default_factory=list)
    timestamp: str | None = None
    warnings: list[str] = field(default_factory=list)
    deferred: bool = False
    """Не писать файлы сразу, а копить до ``commit()``."""
    pending: dict[Path, bytes] = field(default_factory=dict)

    def option(self, name: str) -> OptionValue:
        return self.options[name]

    def str_option(self, name: str) -> str:
        return str(self.options[name])

    def bool_option(self, name: str) -> bool:
        return bool(self.options[name])

    def int_option(self, name: str) -> int:
        value = self.options[name]
        return value if isinstance(value, int) and not isinstance(value, bool) else int(str(value))

    def warn(self, message: str) -> None:
        """Предупреждение генератора: команда печатает его после списка файлов."""
        self.warnings.append(message)

    def header_lines(self) -> list[str]:
        """Строки заголовка сгенерированного файла (без символов комментария)."""
        lines = [
            f"{AUTO_GENERATED} by iolistgen {self.version} — {DO_NOT_EDIT}; источник: {self.source.name}",
            f"SHA-256 перечня {self.source.short_hash}; генератор {self.generator}",
        ]
        if self.timestamp:
            lines.append(f"Время генерации: {self.timestamp}")
        return lines

    def comment_header(self, style: Literal["st", "markdown", "hash"]) -> str:
        """Заголовок в синтаксисе комментариев: ``//`` (ST), ``<!-- -->`` (Markdown), ``#``."""
        lines = self.header_lines()
        if style == "st":
            return "".join(f"// {line}\n" for line in lines)
        if style == "hash":
            return "".join(f"# {line}\n" for line in lines)
        return "<!-- " + "\n     ".join(lines) + " -->\n"

    def write_text(self, relative: str | Path, text: str) -> Path:
        """Записать файл в каталог вывода, только если содержимое изменилось."""
        target = (self.out_dir / relative).resolve()
        root = self.out_dir.resolve()
        if target != root and root not in target.parents:
            raise ValueError(f"генератор {self.generator}: путь {relative} вне каталога вывода")
        data = text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")
        changed = not target.is_file() or target.read_bytes() != data
        if self.deferred:
            # повторная запись того же файла в этом запуске заменяет предыдущую
            self.outputs = [output for output in self.outputs if output.path != target]
            self.pending[target] = data
        elif changed:
            _write(target, data)
        self.outputs.append(OutputFile(target, changed))
        return target

    def commit(self) -> None:
        """Записать отложенные файлы (только изменившиеся)."""
        for output in self.outputs:
            data = self.pending.get(output.path)
            if data is not None and output.changed:
                _write(output.path, data)
        self.pending.clear()


def _write(target: Path, data: bytes) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)


@runtime_checkable
class Generator(Protocol):
    """Генератор (плагин): имя, описание, опции и ``generate()``.

    ``generate`` пишет файлы через ``ctx.write_text()`` и возвращает список записанных путей.
    Имя — строчные латинские буквы, цифры и дефис (``docs-table``, ``st-codesys``).
    """

    @property
    def name(self) -> str: ...

    @property
    def description(self) -> str: ...

    @property
    def options(self) -> Sequence[GeneratorOption]: ...

    def generate(self, model: IoList, out_dir: Path, ctx: GeneratorContext) -> list[Path]: ...


def resolve_options(
    generator: Generator,
    configured: Mapping[str, object] | None = None,
    overrides: Mapping[str, str] | None = None,
) -> dict[str, OptionValue]:
    """Значения опций: умолчания ← ``[generators.<имя>]`` ← ``--set``. ``OptionError`` — неверная опция."""
    specs = {option.name: option for option in generator.options}
    values: dict[str, OptionValue] = {name: spec.default for name, spec in specs.items()}
    for layer in (configured or {}), (overrides or {}):
        for name, raw in layer.items():
            spec = specs.get(name)
            if spec is None:
                known = ", ".join(specs) or "опций нет"
                raise OptionError(f"у генератора {generator.name} нет опции «{name}» ({known})")
            values[name] = spec.parse(raw)
    return values

def context(
    tmp_path: Path, model: IoList, options: dict[str, object] | None = None, name: str = "docs-table"
) -> GeneratorContext:
    generator = DocsTableGenerator()
    return GeneratorContext(
        generator=name,
        out_dir=tmp_path,
        options=resolve_options(generator, options),
        config=Config(),
        source=model.source,
        version=__version__,
    )


@pytest.mark.parametrize(
    ("option", "raw", "value"),
    [
        (GeneratorOption("flag", "", "bool", False), "да", True),
        (GeneratorOption("flag", "", "bool", True), "false", False),
        (GeneratorOption("flag", "", "bool", True), False, False),
        (GeneratorOption("count", "", "int", 1), "42", 42),
        (GeneratorOption("mode", "", "choice", "a", ("a", "b")), "b", "b"),
        (GeneratorOption("name", "", "str", ""), 12, "12"),
    ],
)
def test_option_parse(option: GeneratorOption, raw: object, value: object) -> None:
    assert option.parse(raw) == value



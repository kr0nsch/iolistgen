def test_resolve_options_layers() -> None:
    generator = DocsTableGenerator()
    values = resolve_options(generator, {"title": "Сигналы КНС", "group_by_device": False}, {"filename": "io.md"})
    assert values == {"filename": "io.md", "title": "Сигналы КНС", "group_by_device": False, "plc_variables": True}
    with pytest.raises(OptionError, match="нет опции"):
        resolve_options(generator, {"colour": "red"})


def test_write_text_is_idempotent(tmp_path: Path, model: IoList) -> None:
    ctx = context(tmp_path, model)
    path = ctx.write_text("sub/a.txt", "строка 1\r\nстрока 2\n")
    assert path.read_bytes() == "строка 1\nстрока 2\n".encode()
    stamp = path.stat().st_mtime_ns
    os.utime(path, ns=(stamp - 10_000_000_000, stamp - 10_000_000_000))
    old = path.stat().st_mtime_ns
    ctx.write_text("sub/a.txt", "строка 1\nстрока 2\n")
    assert path.stat().st_mtime_ns == old
    assert [output.changed for output in ctx.outputs] == [True, False]
    ctx.write_text("sub/a.txt", "другое\n")
    assert ctx.outputs[-1].changed


def test_deferred_context_writes_only_on_commit(tmp_path: Path, model: IoList) -> None:
    ctx = context(tmp_path, model)
    ctx.deferred = True
    (tmp_path / "same.txt").write_bytes("без изменений".encode())
    target = ctx.write_text("sub/new.txt", "первый")
    ctx.write_text("sub/new.txt", "второй")  # повторная запись заменяет первую
    ctx.write_text("same.txt", "без изменений")
    assert not target.exists()
    assert [(output.path.name, output.changed) for output in ctx.outputs] == [("new.txt", True), ("same.txt", False)]
    ctx.commit()
    assert target.read_text(encoding="utf-8") == "второй"
    assert ctx.pending == {}



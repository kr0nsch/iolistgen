def test_builtin_registry() -> None:
    entries = discover(entry_points=False)
    assert list(entries) == ["st-codesys", "modbus-map", "scada-csv", "alarm-list", "docs-table"]
    assert all(entry.ok for entry in entries.values())
    assert entries["docs-table"].origin == registry.BUILTIN_ORIGIN
    assert all(isinstance(generator, Generator) for generator in builtin_generators())


PLUGIN_SOURCE = textwrap.dedent(
    """
    from pathlib import Path

    class GoodGenerator:
        name = "custom-csv"
        description = "тестовый плагин"
        options = ()

        def generate(self, model, out_dir: Path, ctx):
            return [ctx.write_text("tags.csv", "tag\\n" + "\\n".join(s.tag for s in model.signals) + "\\n")]

    INSTANCE = GoodGenerator()

    class NotAGenerator:
        name = "broken"

    class Misnamed(GoodGenerator):
        name = "other-name"

    class Upper(GoodGenerator):
        name = "Bad_Name"

    class Shadow(GoodGenerator):
        name = "docs-table"
    """
)


@pytest.fixture
def plugin_module(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    package = tmp_path / "plugins"
    package.mkdir()
    (package / "iolistgen_test_plugin.py").write_text(PLUGIN_SOURCE, encoding="utf-8")
    monkeypatch.syspath_prepend(str(package))
    return "iolistgen_test_plugin"


def fake_entry_points(monkeypatch: pytest.MonkeyPatch, items: list[tuple[str, str]]) -> None:
    points = [metadata.EntryPoint(name=name, value=value, group=ENTRY_POINT_GROUP) for name, value in items]

    def entry_points(*, group: str) -> list[metadata.EntryPoint]:
        assert group == ENTRY_POINT_GROUP
        return points

    monkeypatch.setattr(metadata, "entry_points", entry_points)


def test_entry_point_plugins(monkeypatch: pytest.MonkeyPatch, plugin_module: str) -> None:
    fake_entry_points(
        monkeypatch,
        [
            ("custom-csv", f"{plugin_module}:GoodGenerator"),
            ("instance", f"{plugin_module}:INSTANCE"),
            ("broken", f"{plugin_module}:NotAGenerator"),
            ("missing", "no_such_module_for_iolistgen:Gen"),
            ("misnamed", f"{plugin_module}:Misnamed"),
            ("Bad_Name", f"{plugin_module}:Upper"),
            ("docs-table", f"{plugin_module}:Shadow"),
        ],
    )
    entries = discover()
    assert entries["custom-csv"].ok
    assert entries["custom-csv"].origin == f"{plugin_module}:GoodGenerator"
    assert not entries["instance"].ok and "называется" in (entries["instance"].error or "")
    assert "протоколу" in (entries["broken"].error or "")
    assert "ModuleNotFoundError" in (entries["missing"].error or "")
    assert "называется" in (entries["misnamed"].error or "")
    assert "строчные" in (entries["Bad_Name"].error or "")
    assert entries["docs-table"].ok and entries["docs-table"].origin == registry.BUILTIN_ORIGIN
    shadow = next(e for key, e in entries.items() if key.startswith("docs-table ("))
    assert "уже занято" in (shadow.error or "")


def test_docs_table_generator(tmp_path: Path, model: IoList) -> None:
    generator = DocsTableGenerator()
    ctx = context(tmp_path, model)
    written = generator.generate(model, tmp_path, ctx)
    assert written == [(tmp_path / "docs" / "signal_list.md").resolve()]
    text = written[0].read_text(encoding="utf-8")
    assert text.startswith(f"<!-- {AUTO_GENERATED}")
    assert "Переменная ПЛК |" in text
    assert "| A1.1 | Резервуар | `GVL_IO.rLT101_mA` |" in text
    assert "# Перечень сигналов" in text
    assert "| 11 | `P101` | MotorVfd | `PL.FB_MotorVfd` | Насос Н1 | 6 | Насосы |" in text
    assert "### `LT101` — Уровень в приёмном резервуаре" in text
    assert "уставки: LL 0.5 · L 0.8 · H 4 · HH 4.5 м" in text
    assert "FC3 · 4x 3 · WORD · слейв 1 · RS485-1" in text
    second = context(tmp_path, model)
    generator.generate(model, tmp_path, second)
    assert [output.changed for output in second.outputs] == [False]


def test_docs_table_options(tmp_path: Path, model: IoList) -> None:
    generator = DocsTableGenerator()
    ctx = context(tmp_path, model, {"filename": "docs/io.md", "group_by_device": "false", "title": "Сигналы"})
    path = generator.generate(model, tmp_path, ctx)[0]
    text = path.read_text(encoding="utf-8")
    assert path == (tmp_path / "docs" / "io.md").resolve()
    assert "# Сигналы" in text
    assert "### " not in text
    assert "| Тег | Описание | Устройство |" in text



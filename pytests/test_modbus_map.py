@pytest.fixture(scope="module")
def kns() -> IoList:
    return load(KNS)


@pytest.fixture(scope="module")
def fixture_model() -> IoList:
    return load(FIXTURE)


def read_csv(path: Path, delimiter: str = ";") -> list[dict[str, str]]:
    lines = [line for line in path.read_text(encoding="utf-8").splitlines() if not line.startswith("#")]
    return list(csv.DictReader(io.StringIO("\n".join(lines)), delimiter=delimiter))


def test_master_rows(fixture_model: IoList) -> None:
    rows = master_rows(fixture_model, build_plc(fixture_model))
    by_tag = {str(row["tag"]): row for row in rows}
    assert set(by_tag) == {s.tag for s in fixture_model.modbus_signals()}
    pt = by_tag["PT201"]
    assert (pt["function"], pt["area"], pt["address"], pt["length"], pt["data_type"]) == (4, "3x", 10, 1, "INT")
    assert (pt["raw_min"], pt["raw_max"], pt["eng_min"], pt["eng_max"]) == (0.0, 16000.0, 0.0, 16.0)
    assert "eInput = Raw" in str(pt["scaling"])
    ref = by_tag["P201_REF"]
    assert (ref["direction"], ref["length"], ref["word_order"]) == ("запись", 2, "HL")
    assert ref["plc_variable"] == "GVL_IO.rP201_REF"
    assert "адаптере ПЧ" in str(ref["scaling"])
    keys = [(str(r["link"]), int(str(r["slave"])), str(r["area"]), int(str(r["address"]))) for r in rows]
    assert keys == sorted(keys, key=lambda k: (k[0], k[1], ("0x", "1x", "3x", "4x").index(k[2]), k[3]))


def test_slave_blocks_packed(kns: IoList) -> None:
    blocks = slave_blocks(build_plc(kns), base=100, layout="packed", stride=0)
    assert [b.binding.device.dev_no for b in blocks] == sorted(d.dev_no for d in kns.devices)
    assert blocks[0].start == 100 and blocks[0].registers == 22  # LT101: ST_AnalogInputSts
    for previous, current in itertools.pairwise(blocks):
        assert current.start == previous.end + 1


def test_slave_blocks_by_dev_no(kns: IoList) -> None:
    blocks = slave_blocks(build_plc(kns), base=0, layout="dev_no", stride=40)
    starts = {b.binding.device.ident: b.start for b in blocks}
    assert starts["LT101"] == 40 and starts["P101"] == 440
    with pytest.raises(GenerationError, match="меньше блока"):
        slave_blocks(build_plc(kns), base=0, layout="dev_no", stride=20)
    with pytest.raises(GenerationError, match="65535"):
        slave_blocks(build_plc(kns), base=65000, layout="dev_no", stride=40)


def test_generated_files(tmp_path: Path, kns: IoList) -> None:
    ctx = run(ModbusMapGenerator(), kns, tmp_path)
    assert [p.relative_to(tmp_path.resolve()).as_posix() for p in (o.path for o in ctx.outputs)] == [
        "docs/modbus_master_map.csv",
        "docs/modbus_slave_map.csv",
        "docs/modbus_map.md",
    ]
    master_text = (tmp_path / "docs/modbus_master_map.csv").read_text(encoding="utf-8")
    assert master_text.startswith("# AUTO-GENERATED by iolistgen")
    master = read_csv(tmp_path / "docs/modbus_master_map.csv")
    assert list(master[0]) == list(MASTER_COLUMNS)
    tt = next(row for row in master if row["tag"] == "TT101")
    assert (tt["link"], tt["slave"], tt["area"], tt["word_order"], tt["plc_variable"]) == (
        "RS485-2",
        "10",
        "3x",
        "LH",
        "GVL_IO.rTT101",
    )
    slave = read_csv(tmp_path / "docs/modbus_slave_map.csv")
    assert list(slave[0]) == list(SLAVE_COLUMNS)
    first = slave[0]
    assert (first["device"], first["address"], first["field"], first["data_type"]) == (
        "LT101",
        "0",
        "stSts.stCommon.wStatus",
        "WORD",
    )
    value = next(row for row in slave if row["device"] == "LT101" and row["field"] == "stSts.rValue_eu")
    assert (value["address"], value["length"], value["word_order"]) == ("14", "2", "LH")
    assert value["plc_path"] == "Application.GVL_Devices.fbLT101.stSts.rValue_eu"
    assert sum(1 for row in slave if row["device"] == "P101") == 27  # 14 полей stCommon + 13 полей ST_MotorSts
    md = (tmp_path / "docs/modbus_map.md").read_text(encoding="utf-8")
    assert md.startswith("<!-- AUTO-GENERATED by iolistgen")
    assert "| RS485-2 | 10 | FC4 Read Input Registers | 3x | 0 |" in md
    assert "### `ST_MotorSts` — 34 регистров (MotorVfd)" in md
    assert "| 11 | `P101` | MotorVfd | Насос Н1 |" in md


def test_options(tmp_path: Path, kns: IoList) -> None:
    options = {
        "dir": "maps",
        "delimiter": ",",
        "comment_header": False,
        "slave_area": "input",
        "slave_word_order": "HL",
        "application": "App",
        "slave_layout": "dev_no",
    }
    run(ModbusMapGenerator(), kns, tmp_path, options)
    text = (tmp_path / "maps/modbus_slave_map.csv").read_text(encoding="utf-8")
    assert text.startswith("dev_no,device,")
    slave = read_csv(tmp_path / "maps/modbus_slave_map.csv", ",")
    value = next(row for row in slave if row["device"] == "LT101" and row["field"] == "stSts.rValue_eu")
    assert (value["function"], value["area"], value["word_order"], value["address"]) == ("4", "3x", "HL", "54")
    assert value["plc_path"].startswith("App.GVL_Devices.")
    md = (tmp_path / "maps/modbus_map.md").read_text(encoding="utf-8")
    assert "0 + dev_no · 40" in md and "старшее слово первым" in md


def test_without_slave(tmp_path: Path, kns: IoList) -> None:
    ctx = run(ModbusMapGenerator(), kns, tmp_path, {"slave": False})
    assert len(ctx.outputs) == 2
    assert not (tmp_path / "docs/modbus_slave_map.csv").exists()
    assert "ПЛК — slave" not in (tmp_path / "docs/modbus_map.md").read_text(encoding="utf-8")


def test_list_without_modbus(tmp_path: Path) -> None:
    from iolistgen.validate import check_file
    from pytests.helpers import ai, write_csv

    result = check_file(write_csv(tmp_path / "l.csv", [ai("LT1", 1)]))
    assert result.model is not None
    run(ModbusMapGenerator(), result.model, tmp_path / "out")
    assert "Сигналов Modbus в перечне нет." in (tmp_path / "out/docs/modbus_map.md").read_text(encoding="utf-8")

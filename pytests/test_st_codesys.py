def test_template_dir_overrides(tmp_path: Path, kns: IoList) -> None:
    templates = tmp_path / "tpl" / "st"
    templates.mkdir(parents=True)
    (templates / "GVL_DevIdx.gvl.st.j2").write_text(
        "{{ header }}\n// свой шаблон\n{attribute 'qualified_only'}\nVAR_GLOBAL CONSTANT\n"
        "{% for line in lines %}{{ line }}\n{% endfor %}END_VAR\n",
        encoding="utf-8",
    )
    run(StCodesysGenerator(), kns, tmp_path / "out", {"template_dir": str(tmp_path / "tpl")})
    assert "// свой шаблон" in (tmp_path / "out/src/GVLs/Generated/GVL_DevIdx.gvl.st").read_text(encoding="utf-8")
    with pytest.raises(GenerationError, match="нет каталога"):
        run(StCodesysGenerator(), kns, tmp_path / "out2", {"template_dir": str(tmp_path / "nope")})


def test_generation_is_idempotent(tmp_path: Path, kns: IoList) -> None:
    first = run(StCodesysGenerator(), kns, tmp_path)
    assert all(output.changed for output in first.outputs)
    before = texts(tmp_path)
    second = run(StCodesysGenerator(), kns, tmp_path)
    assert not any(output.changed for output in second.outputs)
    assert texts(tmp_path) == before
    assert second.warnings == []  # тот же перечень — сверка GVL_Persist молчит



def test_cfg_project_suppression_is_needed(generated: Path, tmp_path: Path) -> None:
    """Без lint:allow константы-структуры GVL_CfgProject нарушают STL007 — подавление не лишнее."""
    copy = tmp_path / "copy"
    for name, text in texts(generated).items():
        target = copy / name
        target.parent.mkdir(parents=True, exist_ok=True)
        lines = [line for line in text.splitlines() if "lint:allow" not in line]
        target.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    findings, _ = lint_layout(copy)
    assert findings and {rule for rule, _ in findings} == {"STL007"}



def test_files_are_normalized_and_short(generated: Path) -> None:
    for name, text in texts(generated).items():
        assert text.endswith("\n") and not text.endswith("\n\n"), name
        assert "\r" not in text and "\t" not in text, name
        for number, line in enumerate(text.splitlines(), 1):
            assert line == line.rstrip(), f"{name}:{number}"
            assert len(line) <= 120, f"{name}:{number}: {len(line)} символов"



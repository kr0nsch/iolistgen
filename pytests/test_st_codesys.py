def test_cfg_project_matches_persist(generated: Path) -> None:
    files = texts(generated)
    persist = files["src/GVLs/Generated/GVL_Persist.pvl.st"]
    project = files["src/GVLs/Generated/GVL_CfgProject.gvl.st"]

    def declarations(text: str) -> list[str]:
        blocks = re.findall(r"^    (st\w+Cfg : .*?;)$", text, flags=re.MULTILINE | re.DOTALL)
        return [" ".join(block.split()) for block in blocks]

    assert declarations(project) == declarations(persist)
    assert "VAR_GLOBAL CONSTANT" in project



PREVIOUS = """VAR_GLOBAL PERSISTENT RETAIN
    uiLayoutVersion : UINT := 1;
    // --- dev_no 1: LT101 — Уровень (AnalogInput, без Retain) ---
    stLT101Cfg : PL.ST_AnalogInputCfg := (rRangeHi_eu := 5.0);
    // --- dev_no 11: P101 — Насос Н1 (Motor) ---
    stP101Cfg : PL.ST_MotorCfg;
    stP101Retain : PL.ST_DeviceRetain;
    // --- dev_no 40: OLD1 — Удалённое устройство (DigitalInput, без Retain) ---
    stOLD1Cfg : PL.ST_DigitalInputCfg;
END_VAR
"""


def test_persist_check_messages(kns: IoList) -> None:
    messages = check_persist(PREVIOUS, build_plc(kns))
    text = "\n".join(messages)
    assert "GVL_Persist.stP101Cfg: тип изменился (PL.ST_MotorCfg" not in text  # тип тот же (MotorVfd — ST_MotorCfg)
    assert "GVL_Persist.stOLD1Cfg удалена" in text
    assert "новое устройство LS101 получило dev_no 2, меньше прежнего наибольшего 40" in text
    assert check_persist("", build_plc(kns)) == []


def test_persist_check_type_change_and_reuse(kns: IoList) -> None:
    previous = PREVIOUS.replace("stLT101Cfg : PL.ST_AnalogInputCfg", "stLT101Cfg : PL.ST_DigitalInputCfg").replace(
        "dev_no 11: P101", "dev_no 11: P999"
    )
    text = "\n".join(check_persist(previous, build_plc(kns)))
    assert "GVL_Persist.stLT101Cfg: тип изменился (PL.ST_DigitalInputCfg → PL.ST_AnalogInputCfg)" in text
    assert "dev_no 11 был у P999, теперь у P101" in text


def test_persist_check_runs_on_existing_file(tmp_path: Path, kns: IoList) -> None:
    target = tmp_path / "src/GVLs/Generated/GVL_Persist.pvl.st"
    target.parent.mkdir(parents=True)
    target.write_text(PREVIOUS, encoding="utf-8")
    ctx = run(StCodesysGenerator(), kns, tmp_path)
    assert any("stOLD1Cfg удалена" in message for message in ctx.warnings)
    quiet = run(StCodesysGenerator(), kns, tmp_path / "other", {"persist_check": False})
    assert quiet.warnings == []

"""Эталонные файлы всех встроенных генераторов на малом перечне ``pytests/data/gen_fixture.csv``.

Эталоны лежат в ``pytests/golden/gen_fixture/`` в той же раскладке, что и вывод ``--out .``.
Изменение шаблона, каталога или перечня меняет эталон: проверьте дифф и обновите эталоны
командой ``IOLISTGEN_UPDATE_GOLDEN=1 python -m pytest pytests/test_golden.py`` (в заголовках —
версия iolistgen и SHA-256 перечня, поэтому новая версия тоже обновляет эталоны).
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

import pytest

from iolistgen.generators import builtin_generators
from iolistgen.model import IoList
from pytests.genhelp import FIXTURE, load, run, texts

GOLDEN = Path(__file__).resolve().parent / "golden" / "gen_fixture"
UPDATE = os.environ.get("IOLISTGEN_UPDATE_GOLDEN") == "1"

pytestmark = pytest.mark.golden


@pytest.fixture(scope="module")
def model() -> IoList:
    return load(FIXTURE)


def generate_all(model: IoList, out_dir: Path) -> None:
    for generator in builtin_generators():
        run(generator, model, out_dir)


def test_golden_files(tmp_path: Path, model: IoList) -> None:
    generate_all(model, tmp_path)
    actual = texts(tmp_path)
    if UPDATE:
        if GOLDEN.exists():
            shutil.rmtree(GOLDEN)
        for name, text in actual.items():
            target = GOLDEN / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(text.encode("utf-8"))
    expected = texts(GOLDEN)
    assert sorted(actual) == sorted(expected), "набор файлов изменился — обновите эталоны"
    for name in expected:
        assert actual[name] == expected[name], f"{name} отличается от эталона pytests/golden/gen_fixture/{name}"


def test_second_run_changes_nothing(tmp_path: Path, model: IoList) -> None:
    generate_all(model, tmp_path)
    before = {path: path.stat().st_mtime_ns for path in tmp_path.rglob("*") if path.is_file()}
    snapshot = texts(tmp_path)
    for generator in builtin_generators():
        ctx = run(generator, model, tmp_path)
        assert not any(output.changed for output in ctx.outputs), generator.name
    assert texts(tmp_path) == snapshot
    assert {path: path.stat().st_mtime_ns for path in tmp_path.rglob("*") if path.is_file()} == before


def test_output_does_not_depend_on_directory(tmp_path: Path, model: IoList) -> None:
    generate_all(model, tmp_path / "a")
    generate_all(model, tmp_path / "b" / "nested")
    assert texts(tmp_path / "a") == texts(tmp_path / "b" / "nested")


def test_every_generated_file_has_header(tmp_path: Path, model: IoList) -> None:
    generate_all(model, tmp_path)
    for name, text in texts(tmp_path).items():
        assert "AUTO-GENERATED by iolistgen" in text.splitlines()[0], name
        assert "не редактировать; источник: gen_fixture.csv" in text.splitlines()[0], name
